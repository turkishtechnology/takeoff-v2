import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const scriptFilePath = fileURLToPath(import.meta.url);
const docsFilesDir = path.dirname(scriptFilePath);
const repoRoot = path.resolve(docsFilesDir, '../../../..');
const reactSparTsconfigPath = path.resolve(repoRoot, 'packages/react-spar/tsconfig.json');
const generatedNotice = '<!-- Generated by apps/docs/src/docs-files/generate-mdx.mjs. Do not edit manually. -->';

async function collectApiConfigs(directoryPath, collected = []) {
  const entries = await readdir(directoryPath, { withFileTypes: true });

  for (const entry of entries) {
    const entryPath = path.resolve(directoryPath, entry.name);

    if (entry.isDirectory()) {
      await collectApiConfigs(entryPath, collected);
      continue;
    }

    if (entry.isFile() && entry.name === 'api.config.mjs') {
      collected.push(entryPath);
    }
  }

  return collected;
}

function escapeMarkdownCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ').replaceAll('\r', ' ').trim();
}

function escapeHtml(value) {
  return String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('|', '&#124;');
}

function normalizeType(type) {
  return type
    .replace(/\bundefined\s*\|\s*/gu, '')
    .replace(/\s*\|\s*undefined\b/gu, '')
    .replace(/import\(".*?"\)\.HTMLAttributeAnchorTarget/gu, 'React.HTMLAttributeAnchorTarget')
    .replace(/\bReactNode\b/gu, 'React.ReactNode')
    .replace(/\s+/gu, ' ')
    .trim();
}

function readDefaultTag(symbol) {
  const defaultTag = symbol.getJsDocTags().find(tag => tag.name === 'defaultValue');
  return defaultTag?.text
    ?.map(part => part.text)
    .join('')
    .trim();
}

function getDeclarationForSymbol(symbol) {
  return symbol.valueDeclaration ?? symbol.declarations?.[0];
}

function resolveDeclaration(program, sourceFilePath, typeName) {
  const sourceFile = program.getSourceFile(sourceFilePath);

  if (!sourceFile) {
    throw new Error(`Could not find source file: ${sourceFilePath}`);
  }

  let resolvedDeclaration;

  ts.forEachChild(sourceFile, node => {
    if ((ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) && node.name.text === typeName) {
      resolvedDeclaration = node;
    }
  });

  if (!resolvedDeclaration) {
    throw new Error(`Could not find declaration "${typeName}" in ${sourceFilePath}`);
  }

  return resolvedDeclaration;
}

function getMemberName(memberName) {
  if (!memberName) {
    return null;
  }

  if (ts.isIdentifier(memberName) || ts.isStringLiteral(memberName)) {
    return memberName.text;
  }

  return null;
}

function collectNamesFromTypeNode(typeNode, collected) {
  if (ts.isParenthesizedTypeNode(typeNode)) {
    collectNamesFromTypeNode(typeNode.type, collected);
    return;
  }

  if (ts.isIntersectionTypeNode(typeNode)) {
    for (const memberType of typeNode.types) {
      collectNamesFromTypeNode(memberType, collected);
    }
    return;
  }

  if (ts.isTypeLiteralNode(typeNode)) {
    for (const member of typeNode.members) {
      if (ts.isPropertySignature(member)) {
        const name = getMemberName(member.name);
        if (name) {
          collected.push(name);
        }
      }
    }
  }
}

function collectDeclaredPropNames(declaration) {
  const propNames = [];

  if (ts.isInterfaceDeclaration(declaration)) {
    for (const member of declaration.members) {
      if (ts.isPropertySignature(member)) {
        const name = getMemberName(member.name);
        if (name) {
          propNames.push(name);
        }
      }
    }

    return propNames;
  }

  collectNamesFromTypeNode(declaration.type, propNames);
  return propNames;
}

function buildPropNameOrder(declaration, config) {
  const declarationOrder = collectDeclaredPropNames(declaration);
  const prependPropNames = config.prependPropNames ?? [];
  const appendPropNames = config.appendPropNames ?? [];
  const remainingDeclarationOrder = declarationOrder.filter(propName => !prependPropNames.includes(propName) && !appendPropNames.includes(propName));

  return [...prependPropNames, ...remainingDeclarationOrder, ...appendPropNames].filter((propName, index, propNames) => propNames.indexOf(propName) === index);
}

function buildMemberRows(checker, declaration, config, propNames) {
  const componentType = checker.getTypeAtLocation(declaration);

  return propNames.map(propName => {
    const symbol = componentType.getProperty(propName);

    if (!symbol) {
      throw new Error(`Could not resolve prop "${propName}" for ${config.typeName}`);
    }

    const propDeclaration = getDeclarationForSymbol(symbol);

    if (!propDeclaration) {
      throw new Error(`Could not resolve declaration for prop "${propName}"`);
    }

    const override = config.propOverrides?.[propName];
    const rawType = checker.typeToString(checker.getTypeOfSymbolAtLocation(symbol, propDeclaration), propDeclaration, ts.TypeFormatFlags.NoTruncation);
    const description = override?.description ?? ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim() ?? '';
    const defaultValue = override?.default ?? readDefaultTag(symbol) ?? 'undefined';
    const type = override?.type ?? normalizeType(rawType);

    return {
      name: propName,
      type,
      description,
      defaultValue,
    };
  });
}

function isEventPropName(propName, config) {
  if ((config.eventPropNames ?? []).includes(propName)) {
    return true;
  }

  return /^on[A-Z]/u.test(propName);
}

function buildApiRows(checker, declaration, config) {
  const orderedPropNames = buildPropNameOrder(declaration, config);
  const supplementalEventPropNames = config.eventPropNames ?? [];
  const allPropNames = [...orderedPropNames, ...supplementalEventPropNames].filter((propName, index, propNames) => propNames.indexOf(propName) === index);
  const allRows = buildMemberRows(checker, declaration, config, allPropNames);

  return {
    propRows: allRows.filter(row => !isEventPropName(row.name, config)),
    eventRows: allRows.filter(row => isEventPropName(row.name, config)),
  };
}

function renderTableSection(config, rows, sectionKey, title) {
  if (!rows.length) {
    return '';
  }

  const lines = [`### ${title} {#${config.headingBase}-${sectionKey}}`, '', '| Name | Type | Default | Description |', '| --- | --- | --- | --- |'];

  for (const row of rows) {
    lines.push(
      `| <ApiBadge label="${row.name}" variant="primary" size="large" type="filledlight" /> | <code>${escapeHtml(row.type)}</code> | ${escapeMarkdownCell(row.defaultValue)} | ${escapeMarkdownCell(row.description)} |`,
    );
  }

  return lines.join('\n');
}

function renderDataAttributesSection(config) {
  if (!config.dataAttributes?.length) {
    return '';
  }

  const lines = [`### Data Attributes {#${config.headingBase}-data-attributes}`, '', '| Attribute | Applied when | Purpose |', '| --- | --- | --- |'];

  for (const row of config.dataAttributes) {
    lines.push(`| ${escapeMarkdownCell(row.attribute)} | ${escapeMarkdownCell(row.appliedWhen)} | ${escapeMarkdownCell(row.purpose)} |`);
  }

  return lines.join('\n');
}

async function generateFile(config, checker, declaration, outputFilePath) {
  const { propRows, eventRows } = buildApiRows(checker, declaration, config);
  const output = [generatedNotice, '', "import { ApiBadge } from '@site/src/components/ApiBadge';"];

  const propsSection = renderTableSection(config, propRows, 'props', 'Props');
  if (propsSection) {
    output.push('', propsSection);
  }

  const eventsSection = renderTableSection(config, eventRows, 'events', 'Events');
  if (eventsSection) {
    output.push('', eventsSection);
  }

  const dataAttributesSection = renderDataAttributesSection(config);
  if (dataAttributesSection) {
    output.push('', dataAttributesSection);
  }

  await mkdir(path.dirname(outputFilePath), { recursive: true });
  await writeFile(outputFilePath, `${output.join('\n')}\n`, 'utf8');
}

async function main() {
  const parsedConfig = ts.parseJsonConfigFileContent(ts.readConfigFile(reactSparTsconfigPath, ts.sys.readFile).config, ts.sys, path.dirname(reactSparTsconfigPath));
  const program = ts.createProgram(parsedConfig.fileNames, parsedConfig.options);
  const checker = program.getTypeChecker();
  const configPaths = await collectApiConfigs(docsFilesDir);

  for (const configPath of configPaths) {
    const configModule = await import(pathToFileURL(configPath).href);
    const config = configModule.default;

    if (!config) {
      throw new Error(`Missing default export in ${configPath}`);
    }

    const declaration = resolveDeclaration(program, path.resolve(repoRoot, config.sourceFile), config.typeName);
    const outputFilePath = path.resolve(path.dirname(configPath), 'api.mdx');
    await generateFile(config, checker, declaration, outputFilePath);
  }
}

main().catch(error => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
