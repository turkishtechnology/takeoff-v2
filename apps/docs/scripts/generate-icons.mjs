#!/usr/bin/env node
/* eslint-disable no-console */
/* global process, console */

/**
 * Icon gallery data generator for the takeoff-icons docs instance.
 *
 * Reads the published `@takeoff-icons/core` package (metadata + per-variant SVG
 * data) and emits a single static data module:
 *
 *   src/data/icons.generated.ts
 *
 * The gallery component (`src/components/IconGallery`) consumes ONLY this
 * module, so the page renders from one bundled array rather than hundreds of
 * runtime dynamic imports. Re-run after any icon add/remove/retag:
 *
 *   pnpm --filter docs gen:icons
 *
 * This mirrors the structure of `generate-api-mdx.mjs`: idempotent, prettier
 * formatted, and safe to run repeatedly (a second run produces no diff).
 *
 * Render model (see RFC §4.6 — Hybrid):
 *   - The grid renders from the inlined SVG string of each variant (lightest
 *     bundle, no per-icon React import).
 *   - Copy-paste examples reference the real `@takeoff-icons/react` component
 *     name, derived deterministically from the icon name + variant.
 */

import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';

import prettier from 'prettier';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const docsAppDir = resolve(scriptDir, '..');
const outFile = resolve(docsAppDir, 'src/data/icons.generated.ts');

/**
 * Non-default variant SVGs are emitted as ONE static JSON file per variant —
 * `/icon-svg/<style>-<type>.json`, a map of `{ [iconName]: { viewBox, svg } }`
 * — fetched lazily at runtime when the user switches the toggle. One file per
 * variant (8 files) keeps the repo tidy; the whole variant loads in a single
 * request. We use static files rather than a dynamic `import()` from
 * `@takeoff-icons/core` because the package's `exports` map blocks webpack's
 * dynamic-import context module.
 */
const svgOutDir = resolve(docsAppDir, 'static/icon-svg');

/**
 * Full per-icon inventory in plain Markdown. `generate-llms.mjs` folds this into
 * the gallery page's `.md` mirror, so "Copy page" / "Open in Claude" on a page
 * that renders entirely from React still hand over the actual icon set instead
 * of the two-line frontmatter fallback. Written OUTSIDE `static/icons/` because
 * gen:llms wipes that directory before it writes, and it runs after gen:icons.
 */
const inventoryFile = resolve(docsAppDir, 'static/icons-inventory.md');

/**
 * One line per icon: the kebab name every distribution keys off, the React
 * export for the default variant, and the variants it actually ships (icons are
 * not uniformly covered — see the variant table on the reference page).
 */
function buildInventoryMarkdown(entries, categories) {
  const label = new Map(categories.map(c => [c.id, c.label]));
  const lines = [
    '## Icon inventory',
    '',
    `All **${entries.length}** icons, grouped by category. Each line is \`<name>\` — \`<React export for ${DEFAULT_VARIANT}>\`, then the variants that icon ships.`,
    '',
  ];

  const byCategory = new Map();
  for (const entry of entries) {
    const key = entry.category || 'uncategorized';
    if (!byCategory.has(key)) byCategory.set(key, []);
    byCategory.get(key).push(entry);
  }

  for (const [id, group] of byCategory) {
    lines.push(`### ${label.get(id) ?? id}`, '');
    for (const entry of group) {
      const exportName = reactExportName(entry.name, entry.variants.includes(DEFAULT_VARIANT) ? DEFAULT_VARIANT : entry.variants[0]);
      lines.push(`- \`${entry.name}\` — \`${exportName}\` — variants: ${entry.variants.map(v => `\`${v}\``).join(', ')}`);
    }
    lines.push('');
  }

  return `${lines.join('\n').trim()}\n`;
}

/** Reference page whose marker block is rewritten with generated tables. */
const metadataMdxFile = resolve(docsAppDir, 'icons/metadata.mdx');
const startMarkerToken = 'icons-reference:start';
const endMarkerToken = 'icons-reference:end';
const startMarker = `{/* ${startMarkerToken} (generated by apps/docs/scripts/generate-icons.mjs - do not edit by hand) */}`;
const endMarker = `{/* ${endMarkerToken} */}`;

/** Escape a value for safe rendering inside a Markdown table cell. */
function mdCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ').trim();
}

/**
 * Replace the block between the reference markers in an MDX source string.
 * Mirrors the marker convention used by `generate-api-mdx.mjs` so headings
 * stay in the Docusaurus right-side TOC.
 */
function injectReference(source, generated, targetPath) {
  const startIdx = source.indexOf(`{/* ${startMarkerToken}`);
  const endIdx = source.indexOf(`{/* ${endMarkerToken}`);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) {
    throw new Error(
      `Markers \`${startMarkerToken}\` ... \`${endMarkerToken}\` not found in ${targetPath}.\n` +
        `Add this block where the generated tables should appear:\n\n${startMarker}\n${endMarker}\n`,
    );
  }
  const before = source.slice(0, startIdx);
  const after = source.slice(endIdx + endMarker.length);
  return `${before}${startMarker}\n\n${generated}\n\n${endMarker}${after}`;
}

const STYLES = ['outlined', 'filled'];
const TYPES = ['rounded', 'sharp', 'bevel', 'tk'];

/**
 * Build the generated reference markdown: category counts, variant coverage,
 * and the alias list. Pure function of the icon metadata.
 */
function buildReferenceMarkdown(entries, categories) {
  const lines = [];

  // --- Categories ---------------------------------------------------------
  const countByCategory = new Map();
  for (const e of entries) {
    countByCategory.set(e.category, (countByCategory.get(e.category) ?? 0) + 1);
  }
  lines.push(`## Categories {#categories}`, '');
  lines.push(`There are **${entries.length}** icons across **${categories.length}** categories.`, '');
  lines.push('| Category | ID | Icons | Description |', '| --- | --- | --- | --- |');
  for (const cat of categories) {
    lines.push(`| ${mdCell(cat.label)} | \`${cat.id}\` | ${countByCategory.get(cat.id) ?? 0} | ${mdCell(cat.description)} |`);
  }
  lines.push('');

  // --- Variant coverage ---------------------------------------------------
  lines.push(`## Variant coverage {#variant-coverage}`, '');
  lines.push('How many icons ship each `style/type` variant.', '');
  lines.push('| Variant | Icons |', '| --- | --- |');
  for (const style of STYLES) {
    for (const type of TYPES) {
      const variant = `${style}/${type}`;
      const count = entries.filter(e => e.variants.includes(variant)).length;
      lines.push(`| \`${variant}\` | ${count} |`);
    }
  }
  lines.push('');

  // --- Aliases ------------------------------------------------------------
  const aliased = entries.filter(e => e.aliases.length > 0);
  lines.push(`## Aliases {#aliases}`, '');
  if (aliased.length === 0) {
    lines.push('No icons currently declare aliases.', '');
  } else {
    lines.push(`**${aliased.length}** icons have search aliases.`, '');
    lines.push('| Icon | Aliases |', '| --- | --- |');
    for (const e of aliased) {
      lines.push(`| \`${e.name}\` | ${e.aliases.map(a => `\`${a}\``).join(', ')} |`);
    }
    lines.push('');
  }

  return lines.join('\n').trimEnd();
}

/**
 * The variant previewed by default in the grid. Users can switch style/type in
 * the gallery toggle; this is just the first paint. (RFC §7 decision.)
 */
const DEFAULT_VARIANT = 'outlined/rounded';

/**
 * Resolve a `@takeoff-icons/core` subpath export to an importable URL.
 *
 * The package is ESM-only (its `exports` map has an `import` condition but no
 * `require`), so a CJS `require.resolve` throws ERR_PACKAGE_PATH_NOT_EXPORTED.
 * `import.meta.resolve` uses the ESM resolver and honors the `exports` map,
 * including the multi-segment `./icons/*` wildcard.
 */
function resolveCore(subpath) {
  return import.meta.resolve(`@takeoff-icons/core/${subpath}`);
}

/**
 * Build the `@takeoff-icons/react` named export for a given icon + variant,
 * e.g. ('add', 'outlined/rounded') -> 'AddIconOutlinedRounded'.
 * Mirrors the casing the react package generator uses: PascalCase the kebab
 * name, then append `Icon<Style><Type>`. Digit-leading segments keep the
 * leading underscore the react package emits (e.g. `dialpad-4` -> `Dialpad_4`).
 */
function reactExportName(iconName, variant) {
  const [style, type] = variant.split('/');
  const pascal = segments =>
    segments
      .split('-')
      .map(part => {
        if (!part) return '';
        // The react package prefixes a leading underscore before digit groups
        // produced by splitting (e.g. `dialpad-4` -> `Dialpad` + `_4`).
        const head = /^\d/u.test(part) ? `_${part}` : part;
        return head.charAt(0).toUpperCase() + head.slice(1);
      })
      .join('');
  const cap = s => s.charAt(0).toUpperCase() + s.slice(1);
  return `${pascal(iconName)}Icon${cap(style)}${cap(type)}`;
}

/**
 * Load one variant's SVG data from core, or null if the built module is absent.
 * The core package exposes one module per `icons/<style>/<type>/<name>`,
 * exporting an IconData object: { name, style, type, variant, viewBox, svg }.
 */
async function loadSvg(name, variant) {
  const [style, type] = variant.split('/');
  try {
    const mod = await import(resolveCore(`icons/${style}/${type}/${name}`));
    const data = mod.default ?? Object.values(mod)[0];
    if (data?.svg) return { viewBox: data.viewBox, svg: data.svg };
  } catch {
    // Metadata-listed variant with no built module: treated as a coverage gap.
  }
  return null;
}

async function main() {
  const { iconMetadata, categories } = await import(resolveCore('metadata'));
  const { searchIndex } = await import(resolveCore('search-index'));

  // Index search text by icon name for quick lookup while building entries.
  const searchByName = new Map(searchIndex.map(entry => [entry.name, entry.text]));

  // Inline ONLY the default variant's SVG so the data module stays small. Every
  // OTHER variant is collected into a per-variant map and written as a single
  // JSON file the gallery fetches on demand when the user switches the toggle.
  // (RFC §6 build cost.)
  await rm(svgOutDir, { recursive: true, force: true });
  await mkdir(svgOutDir, { recursive: true });

  // variant -> { [iconName]: { viewBox, svg } }
  const variantMaps = new Map();
  const entries = [];
  for (const meta of iconMetadata) {
    const defaultSvg = meta.variants.includes(DEFAULT_VARIANT) ? await loadSvg(meta.name, DEFAULT_VARIANT) : ((await loadSvg(meta.name, meta.variants[0])) ?? null);

    // Collect non-default variants (default is already inlined per entry).
    for (const variant of meta.variants) {
      if (variant === DEFAULT_VARIANT) continue;
      const svg = await loadSvg(meta.name, variant);
      if (!svg) continue;
      if (!variantMaps.has(variant)) variantMaps.set(variant, {});
      variantMaps.get(variant)[meta.name] = svg;
    }

    entries.push({
      name: meta.name,
      category: meta.category,
      tags: meta.tags,
      aliases: meta.aliases,
      deprecated: meta.deprecated,
      variants: meta.variants,
      searchText: searchByName.get(meta.name) ?? `${meta.name} ${meta.tags.join(' ')}`,
      defaultSvg,
    });
  }

  // Write one file per variant: `<style>-<type>.json`.
  let svgFileCount = 0;
  for (const [variant, map] of variantMaps) {
    const fileName = `${variant.replace('/', '-')}.json`;
    await writeFile(resolve(svgOutDir, fileName), JSON.stringify(map), 'utf8');
    svgFileCount += 1;
  }

  const missing = entries.filter(e => e.defaultSvg === null);
  if (missing.length) {
    console.warn(`⚠ ${missing.length} icon(s) had no resolvable default SVG and will render blank until a variant is fetched.`);
  }

  const fileBody = `// AUTO-GENERATED by apps/docs/scripts/generate-icons.mjs — DO NOT EDIT BY HAND.
// Run \`pnpm --filter docs gen:icons\` to regenerate.

export type IconVariant = string;

export interface IconVariantSvg {
  viewBox: string;
  svg: string;
}

export interface IconGalleryCategory {
  id: string;
  label: string;
  description: string;
}

export interface IconGalleryEntry {
  name: string;
  category: string;
  tags: string[];
  aliases: string[];
  deprecated: boolean;
  variants: IconVariant[];
  searchText: string;
  /** Inlined SVG for the default variant. Other variants load lazily. */
  defaultSvg: IconVariantSvg | null;
}

/** Default variant previewed in the grid before the user changes the toggle. */
export const DEFAULT_VARIANT: IconVariant = ${JSON.stringify(DEFAULT_VARIANT)};

export const iconCategories: IconGalleryCategory[] = ${JSON.stringify(categories, null, 2)};

export const iconEntries: IconGalleryEntry[] = ${JSON.stringify(entries, null, 2)};
`;

  const config = (await prettier.resolveConfig(outFile)) ?? {};
  const formatted = await prettier.format(fileBody, { ...config, filepath: outFile });
  await writeFile(outFile, formatted, 'utf8');

  // Inject the generated reference tables into icons/metadata.mdx.
  await writeFile(inventoryFile, buildInventoryMarkdown(entries, categories), 'utf8');

  const referenceMd = buildReferenceMarkdown(entries, categories);
  let mdxSource;
  try {
    mdxSource = await readFile(metadataMdxFile, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') {
      throw new Error(`Reference page not found: ${metadataMdxFile}. Create it with the ${startMarkerToken}/${endMarkerToken} markers.`, { cause: err });
    }
    throw err;
  }
  const nextMdx = await prettier.format(injectReference(mdxSource, referenceMd, metadataMdxFile), { ...config, filepath: metadataMdxFile });
  if (nextMdx !== mdxSource) {
    await writeFile(metadataMdxFile, nextMdx, 'utf8');
  }

  console.log(
    `✓ ${entries.length} icons → src/data/icons.generated.ts (+ ${svgFileCount} per-variant SVG maps → static/icon-svg/, inventory → static/icons-inventory.md, reference tables → icons/metadata.mdx)`,
  );
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});

export { reactExportName };
