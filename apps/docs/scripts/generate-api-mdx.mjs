#!/usr/bin/env node
/* eslint-disable no-console */
/* global process, console */

/**
 * API table generator for @takeoff-ui/react-spar docs.
 *
 * Discovers `*.api.config.mjs` files under `apps/docs/docs/components/`,
 * resolves the listed component prop interfaces from
 * `packages/react-spar/src/components/.../types.ts` via the TypeScript
 * compiler API, and rewrites the block delimited by
 *
 *   {/* api-tables:start ... *\/}
 *   {/* api-tables:end *\/}
 *
 * markers inside the sibling `<base>.mdx` page.
 *
 * Marker-based injection keeps every heading in the consumer MDX file so the
 * Docusaurus right-side TOC picks up the sub-component menu — partial files
 * imported via `import Foo from './_foo.mdx'` are NOT visited by the TOC
 * remark plugin, so partials would render visually but disappear from the
 * navigation panel.
 *
 * Output shape per component config entry:
 *   ### <displayName> {#<headingBase>}
 *
 *   #### Props {#<headingBase>-props}
 *   | ... |
 *
 *   #### Events {#<headingBase>-events}
 *   | ... |
 *
 *   #### Data attributes {#<headingBase>-data-attributes}
 *   | ... |
 *
 * The h3 sub-component heading lands in the right-side TOC at the default
 * `toc_max_heading_level: 3`; the h4 section labels stay below the fold so
 * the menu reads as a clean list of compound parts.
 *
 * Run from anywhere:
 *   pnpm --filter docs gen:api
 */

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import prettier from 'prettier';
import ts from 'typescript';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const docsAppDir = resolve(scriptDir, '..');
const repoRoot = resolve(docsAppDir, '../..');
const componentsDir = resolve(docsAppDir, 'docs/components');
const tsconfigPath = resolve(repoRoot, 'packages/react-spar/tsconfig.json');
const startMarkerToken = 'api-tables:start';
const endMarkerToken = 'api-tables:end';
const startMarker = `{/* ${startMarkerToken} (generated by apps/docs/scripts/generate-api-mdx.mjs - do not edit by hand) */}`;
const endMarker = `{/* ${endMarkerToken} */}`;

/**
 * Canonical wrapper plumbing props that every takeoff-spar part exposes the
 * same way. When the only props left after filtering Spar-owned ones are in
 * this set, the props table is dropped — consumers can read the customization
 * model once in the shared docs and follow the Spar link for primitive props.
 */
const CANONICAL_PLUMBING_PROPS = new Set(['children', 'className', 'classNames', 'slotProps']);

async function collectConfigPaths(dir, found = []) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      await collectConfigPaths(full, found);
    } else if (entry.isFile() && entry.name.endsWith('.api.config.mjs')) {
      found.push(full);
    }
  }
  return found;
}

function escapeMarkdownCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ').replaceAll('\r', ' ').trim();
}

function escapeHtml(value) {
  return String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('|', '&#124;');
}

function normalizeType(value) {
  let next = value
    .replace(/\bundefined\s*\|\s*/gu, '')
    .replace(/\s*\|\s*undefined\b/gu, '')
    .replace(/import\(".*?"\)\./gu, '')
    .replace(/\bReactNode\b/gu, 'React.ReactNode')
    .replace(/\s+/gu, ' ')
    .trim();
  // Strip a single outer pair of parens (TS often wraps function types).
  while (next.startsWith('(') && next.endsWith(')')) {
    let depth = 0;
    let balanced = true;
    for (let i = 0; i < next.length - 1; i += 1) {
      if (next[i] === '(') depth += 1;
      else if (next[i] === ')') depth -= 1;
      if (depth === 0 && i < next.length - 1) {
        balanced = false;
        break;
      }
    }
    if (!balanced) break;
    next = next.slice(1, -1).trim();
  }
  return next;
}

function normalizeDescription(value) {
  // Resolve `{@link Foo}` JSDoc tags into inline code, since
  // getDocumentationComment leaves them unresolved.
  return String(value).replace(/\{@link\s+([^\s|}]+)(?:\s*\|\s*[^}]+)?\}/gu, '`$1`');
}

function readDefaultTag(symbol) {
  const tag = symbol.getJsDocTags().find(t => t.name === 'defaultValue');
  return tag?.text
    ?.map(part => part.text)
    .join('')
    .trim();
}

function loadProgram() {
  const file = ts.readConfigFile(tsconfigPath, ts.sys.readFile);
  if (file.error) {
    const message = ts.flattenDiagnosticMessageText(file.error.messageText, '\n');
    throw new Error(`Failed to read tsconfig: ${message}`);
  }
  const parsed = ts.parseJsonConfigFileContent(file.config, ts.sys, dirname(tsconfigPath));
  return ts.createProgram({ rootNames: parsed.fileNames, options: parsed.options });
}

function findDeclaration(program, sourceFilePath, typeName) {
  const file = program.getSourceFile(sourceFilePath);
  if (!file) {
    throw new Error(`Source file not found in program: ${sourceFilePath}`);
  }
  let result;
  ts.forEachChild(file, node => {
    if ((ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && node.name.text === typeName) {
      result = node;
    }
  });
  if (!result) {
    throw new Error(`Type "${typeName}" not found in ${sourceFilePath}`);
  }
  return result;
}

function getMemberName(name) {
  if (!name) return null;
  if (ts.isIdentifier(name) || ts.isStringLiteral(name)) return name.text;
  return null;
}

function collectDeclaredPropNames(declaration, checker, seen = new Set()) {
  const names = [];
  const addName = n => {
    if (n && !names.includes(n)) names.push(n);
  };

  if (ts.isInterfaceDeclaration(declaration)) {
    // Collect direct members
    for (const member of declaration.members) {
      if (ts.isPropertySignature(member)) {
        addName(getMemberName(member.name));
      }
    }
    // Collect inherited members from Pick<...> types in extends clauses.
    // Skip Omit<ComponentPropsWithoutRef<...>, ...> which provides native HTML
    // attributes — those are always available and don't belong in the table.
    if (declaration.heritageClauses && checker) {
      for (const clause of declaration.heritageClauses) {
        for (const typeExpr of clause.types) {
          // Only resolve Pick utility types — they carry intentionally chosen
          // Spar props. Omit/ComponentPropsWithoutRef carry hundreds of native
          // HTML attributes that would flood the table.
          const exprText = typeExpr.expression?.getText?.() ?? '';
          if (exprText !== 'Pick') continue;
          const heritageType = checker.getTypeAtLocation(typeExpr);
          for (const prop of heritageType.getProperties()) {
            addName(prop.name);
          }
        }
      }
    }
    return names;
  }

  const visit = node => {
    if (ts.isParenthesizedTypeNode(node)) {
      visit(node.type);
    } else if (ts.isIntersectionTypeNode(node)) {
      for (const t of node.types) visit(t);
    } else if (ts.isTypeLiteralNode(node)) {
      for (const m of node.members) {
        if (ts.isPropertySignature(m)) {
          addName(getMemberName(m.name));
        }
      }
    } else if (ts.isTypeReferenceNode(node)) {
      const refName = node.typeName?.getText?.() ?? '';
      // PolymorphicProps<TDefault, T, OwnProps> — only walk the third arg.
      // The wrapper itself adds `as` plus Omit<ComponentPropsWithRef<...>>,
      // which would flood the table with native HTML attributes.
      if (refName === 'PolymorphicProps') {
        const args = node.typeArguments ?? [];
        if (args.length >= 3) visit(args[2]);
        return;
      }
      // Pick<T, K> — resolve via checker for the listed keys only.
      if (refName === 'Pick' && checker) {
        const picked = checker.getTypeAtLocation(node);
        for (const prop of picked.getProperties()) {
          addName(prop.name);
        }
        return;
      }
      // Other type references — typically a user-authored interface like
      // `AccordionOwnProps`. Resolve the symbol to its declaration and recurse
      // so nested intersections / Pick<>s inside it get the same treatment.
      if (checker) {
        const symbol = checker.getSymbolAtLocation(node.typeName);
        const decls = symbol?.declarations ?? [];
        for (const decl of decls) {
          if (!(ts.isInterfaceDeclaration(decl) || ts.isTypeAliasDeclaration(decl))) continue;
          // Guard against cycles (mutually-recursive aliases) and avoid
          // re-walking the same declaration twice in a single pass.
          if (seen.has(decl)) continue;
          seen.add(decl);
          for (const n of collectDeclaredPropNames(decl, checker, seen)) {
            addName(n);
          }
        }
      }
    }
  };
  visit(declaration.type);
  return names;
}

function buildPropNameOrder(declaration, config, checker) {
  const declared = collectDeclaredPropNames(declaration, checker);
  const prepend = config.prependPropNames ?? [];
  const append = config.appendPropNames ?? [];
  const skip = new Set([...(config.skipPropNames ?? []), ...(config.sparBehaviorProps ?? [])]);
  const middle = declared.filter(n => !prepend.includes(n) && !append.includes(n) && !skip.has(n));
  const merged = [...prepend, ...middle, ...append].filter(n => !skip.has(n));
  return merged.filter((n, i, arr) => arr.indexOf(n) === i);
}

function buildRowsForComponent(checker, declaration, config) {
  const type = checker.getTypeAtLocation(declaration);
  const propNames = buildPropNameOrder(declaration, config, checker);
  const overrides = config.propOverrides ?? {};
  const propRows = [];
  const eventRows = [];

  for (const name of propNames) {
    const symbol = type.getProperty(name);
    let typeText = '';
    let description = '';
    let defaultText;

    if (symbol) {
      const propType = checker.getTypeOfSymbolAtLocation(symbol, declaration);
      typeText = normalizeType(checker.typeToString(propType, declaration, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope));
      description = normalizeDescription(ts.displayPartsToString(symbol.getDocumentationComment(checker)));
      defaultText = readDefaultTag(symbol);
    }

    const override = overrides[name] ?? {};
    typeText = override.type ?? typeText;
    description = override.description ?? description;
    defaultText = override.default ?? defaultText;
    if (!defaultText || defaultText === '') defaultText = '-';

    const isEvent = /^on[A-Z]/u.test(name);
    (isEvent ? eventRows : propRows).push({
      name,
      type: typeText,
      default: defaultText,
      description,
    });
  }

  return { propRows, eventRows };
}

function renderTable(headers, rows) {
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const data = rows.map(r => `| ${r.join(' | ')} |`);
  return [head, sep, ...data].join('\n');
}

function renderPropRow(row) {
  return [`<ApiBadge label="${row.name}" />`, `<code>${escapeHtml(row.type)}</code>`, escapeMarkdownCell(row.default), escapeMarkdownCell(row.description)];
}

function renderDataAttrRow(attr) {
  return [`\`${attr.attribute}\``, escapeMarkdownCell(attr.appliedWhen), escapeMarkdownCell(attr.purpose)];
}

function renderSparBehaviorNote(component) {
  if (!component.sparDocsUrl) return null;

  const label = component.sparDocsLabel ?? 'Spar docs';

  return `See [${label}](${component.sparDocsUrl}) for primitive behavior.`;
}

function hasNonPlumbingProp(rows) {
  return rows.some(r => !CANONICAL_PLUMBING_PROPS.has(r.name));
}

function renderComponentSection(component, rows) {
  const lines = [];
  const heading = component.displayName ?? component.typeName;
  const base = component.headingBase;
  const { propRows, eventRows } = rows;

  lines.push(`### ${heading} {#${base}}`);
  lines.push('');

  const sparBehaviorNote = renderSparBehaviorNote(component);
  if (sparBehaviorNote) {
    lines.push(sparBehaviorNote);
    lines.push('');
  }

  if (hasNonPlumbingProp(propRows)) {
    lines.push(`#### Props {#${base}-props}`);
    lines.push('');
    lines.push(renderTable(['Name', 'Type', 'Default', 'Description'], propRows.map(renderPropRow)));
    lines.push('');
  }

  if (eventRows.length) {
    lines.push(`#### Events {#${base}-events}`);
    lines.push('');
    lines.push(renderTable(['Name', 'Type', 'Default', 'Description'], eventRows.map(renderPropRow)));
    lines.push('');
  }

  if (component.dataAttributes?.length) {
    lines.push(`#### Data attributes {#${base}-data-attributes}`);
    lines.push('');
    lines.push(renderTable(['Attribute', 'Applied when', 'Purpose'], component.dataAttributes.map(renderDataAttrRow)));
    lines.push('');
  }

  return lines.join('\n').trimEnd();
}

function injectIntoMdx(source, generated, targetPath) {
  const startIdx = source.indexOf(`{/* ${startMarkerToken}`);
  const endIdx = source.indexOf(`{/* ${endMarkerToken}`);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) {
    throw new Error(
      `Markers \`${startMarkerToken}\` ... \`${endMarkerToken}\` not found in ${targetPath}.\n` +
        `Add the following block where the API tables should appear:\n\n` +
        `${startMarker}\n${endMarker}\n`,
    );
  }
  const startEnd = source.indexOf('*/}', startIdx);
  if (startEnd === -1 || startEnd > endIdx) {
    throw new Error(`Malformed start marker in ${targetPath}.`);
  }
  const before = source.slice(0, startIdx);
  const after = source.slice(endIdx + endMarker.length);
  const block = `${startMarker}\n\n${generated}\n\n${endMarker}`;
  return before + block + after;
}

async function formatGeneratedMdx(generated, targetPath) {
  const config = (await prettier.resolveConfig(targetPath)) ?? {};
  return (await prettier.format(generated, { ...config, filepath: targetPath })).trimEnd();
}

async function generateForConfig(program, checker, configPath) {
  const url = pathToFileURL(configPath).href;
  const mod = await import(url);
  const config = mod.default ?? mod;
  const components = Array.isArray(config.components) ? config.components : [config];

  const sections = [];
  for (const comp of components) {
    const sourceFilePath = resolve(repoRoot, comp.sourceFile);
    const declaration = findDeclaration(program, sourceFilePath, comp.typeName);
    const rows = buildRowsForComponent(checker, declaration, comp);
    sections.push(renderComponentSection(comp, rows));
  }

  const dir = dirname(configPath);
  const base = basename(configPath, '.api.config.mjs');
  const targetPath = resolve(dir, `${base}.mdx`);

  let source;
  try {
    source = await readFile(targetPath, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') {
      throw new Error(`Page not found: ${targetPath} (expected sibling of ${configPath})`, { cause: err });
    }
    throw err;
  }

  const generated = await formatGeneratedMdx(sections.join('\n\n'), targetPath);
  const next = injectIntoMdx(source, generated, targetPath);
  if (next !== source) {
    await writeFile(targetPath, next, 'utf8');
  }
  return targetPath;
}

async function main() {
  const program = loadProgram();
  const checker = program.getTypeChecker();

  const configs = await collectConfigPaths(componentsDir);
  if (!configs.length) {
    console.warn(`No *.api.config.mjs found under ${relative(repoRoot, componentsDir)}`);
    return;
  }

  for (const cfg of configs) {
    const out = await generateForConfig(program, checker, cfg);
    console.log(`✓ ${relative(repoRoot, out)}`);
  }
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
