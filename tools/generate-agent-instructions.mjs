#!/usr/bin/env node

/* eslint-disable no-console */

/**
 * Generates the tool-agnostic agent instruction files from the per-component
 * skills, so every assistant the company uses gets the same guidance.
 *
 * Claude Code reads `.agents/skills/**` natively. GitHub Copilot, Cursor, and
 * the other assistants in use do not — they read a single instructions file at
 * a well-known path. Rather than maintaining that guidance twice (which drifts),
 * both outputs below are derived from the skills:
 *
 *   .github/copilot-instructions.md
 *     Read automatically by GitHub Copilot for work *inside this repo*.
 *
 *   packages/react-spar/agents/AGENTS.template.md
 *     Ships in the npm package. Consumers copy it to their own repo root as
 *     AGENTS.md — the de-facto standard that Copilot, Cursor, and Claude all
 *     read — so projects that only ever install the package still get the
 *     component map and the house rules.
 *
 * The two repo-workflow skills are deliberately excluded: they hard-require
 * files that exist only in this monorepo and would dead-end elsewhere.
 *
 * Run via: pnpm gen:agent-instructions  (verify in CI with --check)
 */

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '..');
const skillsDir = join(repoRoot, '.agents/skills');

const DOCS_URL = 'https://takeoff-v2.app.turkishtechlab.com';
const NON_COMPONENT_SKILLS = new Set(['takeoff-ui', 'takeoff-component-workflow']);

const OUTPUTS = {
  copilot: join(repoRoot, '.github/copilot-instructions.md'),
  template: join(repoRoot, 'packages/react-spar/agents/AGENTS.template.md'),
};

const checkMode = process.argv.includes('--check');

// --- read the skills ---------------------------------------------------------

function parseFrontmatter(raw) {
  const match = raw.match(/^---\n([\s\S]*?)\n---\n?/u);
  if (!match) return { data: {}, body: raw };
  const data = {};
  const lines = match[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const keyMatch = lines[i].match(/^([A-Za-z_][\w-]*):\s*(.*)$/u);
    if (!keyMatch) continue;
    const key = keyMatch[1];
    let value = keyMatch[2];
    if (value === '') {
      const parts = [];
      while (i + 1 < lines.length && /^\s+\S/u.test(lines[i + 1])) parts.push(lines[++i].trim());
      value = parts.join(' ');
    }
    data[key] = value.replace(/^['"]|['"]$/gu, '');
  }
  return { data, body: raw.slice(match[0].length) };
}

/** One-line summary of what a component is for, taken from its skill. */
function summarize(body) {
  // Prefer the explicit "When to use" lead-in; fall back to the first real
  // paragraph so the five "Quick start" skills still get a sentence.
  const whenToUse = body.match(/^\*\*When to use:\*\*\s*([\s\S]*?)(?=\n\s*\n)/mu)?.[1];
  const source =
    whenToUse ??
    body
      .split(/\n## /u)[0]
      // Trim first: the body starts with the blank lines that followed the
      // frontmatter, so an un-anchored `^` would never see the heading.
      .trim()
      // Drop every leading ATX heading ("# Divider — @takeoff-ui/react-spar"),
      // otherwise the title bleeds into the summary for the "Quick start" skills.
      .replace(/^(#[^\n]*\n+)+/u, '')
      .trim();
  const flat = source.replace(/\s+/gu, ' ').trim();
  // First sentence only — these are index entries, not documentation.
  const sentence = flat.match(/^.*?[.!?](?=\s|$)/u)?.[0] ?? flat;
  // "Reach for `Badge` for inline status pills" reads as noise in a table whose
  // first column is already the component name.
  const trimmed = sentence.replace(/^(Reach for\s+`?\w+`?\s+(?:for|whenever|when)\s+)/iu, '').replace(/^Use\s+`?\w+`?\s+(?:for|to|when|whenever)\s+/iu, '');
  const normalized = trimmed.charAt(0).toUpperCase() + trimmed.slice(1);
  return normalized.length > 200 ? `${normalized.slice(0, 197).trimEnd()}…` : normalized;
}

const components = readdirSync(skillsDir, { withFileTypes: true })
  .filter(e => e.isDirectory() && e.name.startsWith('takeoff-') && !NON_COMPONENT_SKILLS.has(e.name))
  .map(e => e.name)
  .sort()
  .map(name => {
    const slug = name.slice('takeoff-'.length);
    const { body } = parseFrontmatter(readFileSync(join(skillsDir, name, 'SKILL.md'), 'utf8'));
    const exported = slug.replace(/(^|-)([a-z])/gu, (_, __, c) => c.toUpperCase());
    return { slug, exported, summary: summarize(body) };
  });

// --- shared body -------------------------------------------------------------

const GENERATED_NOTE = '<!-- Generated by tools/generate-agent-instructions.mjs from .agents/skills. Do not edit by hand. -->';

function componentTable() {
  return ['| Component | Use it for |', '| --- | --- |', ...components.map(c => `| \`${c.exported}\` | ${c.summary} |`)].join('\n');
}

const HOUSE_RULES = `## Rules

- Import every component from \`@takeoff-ui/react-spar\`. Do not hand-roll an
  element that already exists in the table below — reach for the component.
- React 19 only. React 18 throws at runtime.
- Mount \`TakeoffSparProvider\` once at the app root and import the token CSS
  (\`@takeoff-design/tokens/css/default/theme.css\`) once at the entry point.
- Style through the documented layers only: \`className\` (root slot),
  \`classNames={{ slot }}\`, \`slotProps={{ slot }}\`, or provider defaults.
  Internal DOM is not a styling contract — only rely on documented
  \`data-*\` attributes.
- Icons ship separately in \`@takeoff-icons/react\`.`;

function usageSection() {
  return `## Getting the full API

This file is an index. For a component's complete props, slots, data attributes,
and runnable examples, fetch its Markdown page:

    ${DOCS_URL}/docs/components/<component>.md

The entire library in one file (for pasting into a model's context) is at:

    ${DOCS_URL}/llms-full.txt`;
}

// --- outputs -----------------------------------------------------------------

function copilotDoc() {
  return `${GENERATED_NOTE}

# @takeoff-ui/react-spar — Copilot instructions

This repository builds and documents \`@takeoff-ui/react-spar\`, a React 19
component library wrapping the headless Spar primitives with Takeoff design
tokens.

When writing or reviewing UI code here, follow the rules below.

${HOUSE_RULES}

## Components

${componentTable()}

${usageSection()}

## Working on the library itself

Changing the library (not just using it) has extra rules — upstream-first
fixes, the \`Pick<>\` prop boundary, the public compound policy. Those live in
[\`AGENTS.md\`](../AGENTS.md) and
[\`docs/component-authoring-contract.md\`](../docs/component-authoring-contract.md).
`;
}

function templateDoc() {
  return `${GENERATED_NOTE}

# AGENTS.md — @takeoff-ui/react-spar

> Copy this file to the root of the project that consumes
> \`@takeoff-ui/react-spar\` and rename it \`AGENTS.md\`. GitHub Copilot,
> Cursor, and Claude all read it automatically. Add your own project rules
> below the generated sections.

This project uses \`@takeoff-ui/react-spar\`, a React 19 component library built
on headless Spar primitives and styled with Takeoff design tokens.

${HOUSE_RULES}

## Components

${componentTable()}

${usageSection()}
`;
}

// --- write / check -----------------------------------------------------------

// Run the output through Prettier with the repo config. Both the pre-commit
// hook and `format:check` would otherwise reformat these files after
// generation, leaving `--check` permanently dirty in CI.
async function formatMarkdown(content, filepath) {
  const config = await prettier.resolveConfig(filepath);
  return prettier.format(content, { ...config, filepath, parser: 'markdown' });
}

const artifacts = [
  { path: OUTPUTS.copilot, content: await formatMarkdown(copilotDoc(), OUTPUTS.copilot) },
  { path: OUTPUTS.template, content: await formatMarkdown(templateDoc(), OUTPUTS.template) },
];

if (checkMode) {
  const stale = [];
  for (const { path, content } of artifacts) {
    let current = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== content) stale.push(path.replace(`${repoRoot}/`, ''));
  }
  if (stale.length > 0) {
    console.error('Agent instruction files are out of date with .agents/skills:');
    for (const path of stale) console.error(`  - ${path}`);
    console.error('\nFix: run `pnpm gen:agent-instructions` and commit the result.');
    process.exit(1);
  }
  console.log(`Agent instructions are in sync (${components.length} components).`);
} else {
  for (const { path, content } of artifacts) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path.replace(`${repoRoot}/`, '')}`);
  }
  console.log(`Generated agent instructions from ${components.length} component skills.`);
}
